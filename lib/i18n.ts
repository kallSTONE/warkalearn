export function normalizeLocale(input?: string | null): Locale | null {
  if (!input) return null;
  const normalized = input.toLowerCase().trim();
  const baseLocale = normalized.split('-')[0];

  if ((SUPPORTED_LOCALES as readonly string[]).includes(baseLocale)) {
    return baseLocale as Locale;
  }

  return null;
}

export function getDictionary(locale: Locale): Dictionary {
  return DICTIONARIES[locale] ?? DICTIONARIES[DEFAULT_LOCALE];
}

export function translate(locale: Locale, key: string, fallback?: string): string {
  const dictionary = getDictionary(locale);
  return dictionary[key] ?? fallback ?? key;
}

export function readLocaleFromCookieValue(cookieValue?: string | null): Locale | null {
  return normalizeLocale(cookieValue);
}
